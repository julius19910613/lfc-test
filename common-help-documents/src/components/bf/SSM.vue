    <h1>标准问题匹配（SSM）使用指南</h1>
    <p>标准问题匹配是我们训练机器人对客户对企业咨询问题时达到回应正确答案的能力。要让机器人正确回答问题，
        我们需要让机器人理解客户问的是什么问题？（标准问题）而客户会如何询问（训练语料），我们需要让机器人尽可
        能的理解客户咨询问题时的不同问法（训练），为了保证质量，我们还需要对训练后的机器人进行考核（测试）。最后发
        布上线后才能上线为客户提供最专业的服务（接入）</p>
    <h1>标准问题</h1>
    <h2>什么是标准问题？</h2>
    <p>标准问题是用户询问客服的业务问题。</p>
    <p>“我的包裹到哪去了？”和“我的快递到了没啊？”这些语料中的语义相同，为了让我们更便利的管理这
        些类似的问题，我们可以把这些问题分类为“快递查询”。而这个“快递查询“可以称为标准问题。我们也可以直接使用现有的标准问题。</p>
    <h2>为什么需要标准问题？</h2>
    <p>设定标准问题可以让我们更好的梳理业务问题，将不同的业务问题设计成标准问题后，用户询问的问题就能够被正确的理解并得到合适的回复。</p>
    <h2>该从哪里获得现有的标准问题？</h2>
    <p>如果不知道该怎么设计，我们可以寻找现有的标准问题。</p>
    <p>1. 如果曾使用过智能客服，我们可以直接使用当中的标准问题，也可以进行优化。</p>
    <p>2. 如果有人工客服，我们可以从客服手册等培训材料中得到用户常问的问题。 如果没有用户
        日志，我们依然可以利用本身对业务的了解自己设计标准问题，那我们就需要知道该如何设计良好的标准问题。</p>
    <h2>如何设计良好的标准问题？</h2>
    <p>标准问题对机器人来说非常重要，标准问题设计的好坏会直接影响到您的训练后正确率，需要认真对每个标准问题进行严谨的思考。在设计标准问题的时候需要注意以下几点：</p>
    <p>1、首先找到用户最常问的问题类型，先为它们设计标准问题。</p>
    <p>2、在设计标准问题时，需要明确区分，不要出现容易误解、混淆的标准问题。</p>
    <p>3、请不要设计有包含关系的标准问题（“公司的电话”这个标准问题可能也包含了“上海分公司的电话”）</p>
    <p>4、请不要设计两个名字很像、容易产生误解的标准问题（例如“个人主页无法显示”和“个人主页显示异常”）</p>
    <h2>标准问题模板是什么？为什么需要模板？</h2>
    <p>服务器只能接受特定格式的文档，所以希望在上传数据之前，请先下载我们的模板，按
        照模板的样式整理数据。标准问题的模板非常简单，它是这个样子的：只要把问题放在
        第一列，回答放在第二列，就可以了。整理好之后，记得保存为xlsx格式（excel2007及以后版本的文件格式）。</p>
    <h1>训练语料</h1>
    <h2>什么是训练语料？</h2>
    <p>一个标准问题会有不同的问法，这些不同种的问法就是训练语料，可以让机器人学习哪些问法对应了哪个标准问题，提高机器人识别标准问题正确率。</p>
    <p>机器人是根据语料来学习的。对于机器人来说，最好的语料是来自用户与客服人员对话的用户
        日志。但是很多时候我们没有办法得到用户日志，就需要自己模仿用户对每个标准问题写语料。
        为了方便您的使用，我们会将您添加的标准问题作为自身的语料数据。</p>
    <h2>什么是用户日志？</h2>
    <p>用户日志是用户与客服对话的记录列表。</p>
    <p>用户会对客服机器人问的各种不同问题，这些从用户手里获取到的第一手语料会更贴近用户的问法，这样的语料具有更高的质量。</p>
    <h2>什么是扩写？</h2>
    <p>扩写就是模拟用户可能的问法所设计的问题，进行扩写的时候需要注意以下几点：</p>
    <p>1、需要模仿用户对标准问题的不同问法。</p>
    <p>一个人的想法总是有限的，可以请几个人提供扩写语料，能覆盖更多的问法种类。</p>
    <h2>我该对每个标准问题准备多少条的语料？</h2>
    <p>根据我们的经验来看，10-30条的语料可以达到基本的正确率、30-50条语料可以达到中等的正确率、50-70条则可以达到精确的正确率。</p>
    <p>在某些项目中，有些标准问题达到100条以上，机器人正确回答的能力就更高了。建议在每个标注问题中准备至少10条以上的语料来确保机器人的回答质量。</p>

