    <h1>训练</h1>
    <h2>什么是训练？</h2>
    <p>训练是让机器人学习的过程，我们将前面准备的语料和标准问题的对
        应关系放入模型，通过深度学习等人工智能技术，机器人就获得了回答相关问
        题的能力。可以说我们前面的语料增加和标注，都是为了训练提供基础，我们提供的语料越丰富、有代表性，训练出的机器人的问题回答能力就越强。</p>
    <h2>什么时候可以进行训练？</h2>
    <p>一个机器人需要有标准问题以及足够的训练语料，我们推荐为每个标准问题尽
        量提供10条以上的训练语料。当我们为每个标准问题都准备了充足的语料之后，就可以开始训练啦！我们的机器人就会依照您提供的信息学习用户语料是如何对应标准问题咯！</p>
    <p>当我们为每个标准问题都准备了充足的语料之后，就可以开始训练啦！我们的机器人就会依照您提供的信息学习用户语料是如何对应标准问题咯！</p>
    <h2>什么时候进行新一轮的训练？</h2>
    <p>1、新增或修改了原有的标准问题时。</p>
    <p>2、新增了新的训练语料。</p>
    <p>完成测试后，根据对应的正确率，对标准问题、语料进行了一些修改之后就可以开始新的训练；或在您增加了一批新的标准问题、新的语料后，也可以进行新的训练。</p>
    <p>总之在标准问题和语料有了比较多的改变之后都可以进行训练，来看看这些改变对机器人的效果如何。</p>
    <h2>需要多少语料才可以进行训练呢？</h2>
    <p>根据我们的经验来看，10-30条的语料可以达到基本的正确率、
        30-50条语料可以达到中等的正确率、50-70条则可以达到精确的正确率。在某些项目中，有些标
        准问题达到100条以上，机器人正确回答的能力就更高了。建议在每个标注问题中准备至少10条以上的语料来确保机器人的回答质量。</p>
    <h1>测试</h1>
    <h2>什么是测试？</h2>
    <p>我们训练好了机器人后，会需要一些测试题来检验机器人的学习效果。</p>
    <p>测试是模拟机器人面对真实用户时，是不是可以正确识别用户的
        提问属于哪个标准问题。为了让客户有个很棒的客服体验，我们需要确保较高的正确率。我们通过测试来了解机器人对语料的理解效果，找出机器人理解较差的标准问题，优化到令人满意的正确率。</p>
   <h2>该如何准备测试题？</h2>
    <p>准备测试集设计的好坏会影响到测试结果，以下提供几点建议：</p>
    <p>1、问法要尽可能贴近真实用户的问法，最好是之前留下的用户日志，如果没有，也可以请公司内部最贴近客户的员工来模仿客户的问法。</p>
    <p>2、您可以对每一个标准问题准备多点测试题，才可以真正反映标准问题的正确率，不然只能一题定生死，还是有些偏差的。</p>
    <p>3、可以按照标准问题被询问的频率来定测试题的数量，越常被问到就准备越多的测试题。建议可以让比较了解的同事粗略估计一下。</p>
    <p>4、当然，要确定您的测试题对应的“正确标准问题”是对的。有时候也会有不小心写错“正确标准问题”的状况发生。</p>
    <p>5、还有个小建议，当您从用户日志抽问题作为您的测试集时，需要检查一下这个问题里面是不是包含了好多个问题，或是句子很长，这个也会影响到测试结果。</p>
    <h2>测试集该怎么写呢？</h2>
    <p>你可以使用机器人工厂中编辑工具撰写测试题，你也可以使用我们提供的Excel模板来上传测试题。</p>
    <p>有件事情需要注意的是，表格当中的“正确标准问题”栏中的标准问题内容需要和系统中的标准问题一模一样，否则系统无法正确地判断。</p>
    <p>我们需要把给机器人的考题放进一个模板里，第一列放的是
        测试题，是用户可能问的问题，第二列则是正确答案，也就是这个语料应该对应的标准问题。上传后，系统会记录机器人对每个题目的答案，算出回答正确的比例，即测试结果。</p>
    <h2>什么时候可以开始测试？</h2>
    <p>在训练过后，我们就可以开始测试了。训练之前可以参考我们的小贴士（Tips：我还想让我的结果更好）</p>
    <p>正常的机器人训练和测试的流程</p>
    <p>正常情况下，当你建立新的机器人时，有以下几点需要准备：</p>
    <p>1、你需要针对每个标准问题准备训练语料</p>
    <p>2、每个标准问题要有3-4个标准问题，如果想要测试机器人对标准问题的覆盖率，你也可以增加更多的测试题。</p>
    <p>3、接下来你就可以训练并测试机器人了</p>
    <p>4、查看你的测试结果，如果出现真确率时，你可以查看我们的小贴士（我还想让我的结果更好</p>
    <h2>什么是正确率？</h2>
    <p>正确率是每次测试中，机器人预测正确的测试题在所有测试题中所占的比例。</p>
    <p>为什么我的标准问题正确率是N/A呢？</p>
    <p>要得到每个标准问题的正确率，需要在测试结束后才会出现。没有测试题的标准问题也会出现N/A这个状态。</p>
    <h2>什么是发布？</h2>
    <p>发布上线指的是将当前已训练的最新数据应用于用户的对话中。
        对话场景包括页面的线上对话，机器人已接入的各个渠道对话，比如微信公众号、
        企业微信，APP等。前面维护标准问答，数据训练和测试及报告均是线下操作，不会
        影响线上的数据和对话效果。审核者可以在【变更记录】审核过后，将上述变更数据进行训练，并发布到线上应用。</p>
    <p>标准问题和语料变更后，需要重新训练，建立新的模型。回答变更无需训练，所以分开两部分发布。如果想让变更的回答快速生效，可以只选择回答单独发布。</p>
