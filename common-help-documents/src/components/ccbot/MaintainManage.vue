        点击【详情】进入场景详情页面，可以发现该场景话术均已同步至详情，点击【一键生成】则生成话术的TTS录音。
    </p>
    <p>
        标准问答的语音素材也是类似的操作，点击右上角的【导入标准问答方案】，
        选择对应的机器人和TTS服务，再点击【详情】进入详情页面【同步标准问】，
        同步成功后，页面会显示该机器人下所有标准问答内容。点击【一键生成】则生成话术的TTS录音。
    </p>
