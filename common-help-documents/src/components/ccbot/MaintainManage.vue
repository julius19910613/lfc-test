<p>在电话机器人中，为了保证能够更好的理解用户的表达，一般会使用到机器人平台的标准问题和任务引擎模块，
    场景语音素材则是对应机器人平台中任务引擎模块，标准问答语音素材则对应机器人平台中问答管理模块，可以将不同模块的话术内容生成为语音素材。</p>
